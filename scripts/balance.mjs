// Balance report: plays the whole design as the par player and checks it against src/design/targets.js.
//   npm run balance            writes docs/BALANCE.md and prints the warnings
//   npm run balance -- --quiet only prints the summary line;  --no-write skips writing the report (npm test uses both)
// Exit code is 0 even with warnings: they're design notes, not test failures.
import { writeFileSync } from 'node:fs';
import { simGame } from '../src/design/sim.js';
import { validate } from '../src/design/validate.js';
import { TARGETS as T } from '../src/design/targets.js';
import { xpNeed, affixTiers, grow, skillHit, sumMods } from '../src/design/formulas.js';
import { LEVEL } from '../src/design/progression.js';
import { AFFIXES, BASES, UNIQUES } from '../src/design/items.js';
import { SKILLS } from '../src/design/skills.js';
import { SCALE, BOSSES } from '../src/design/monsters.js';
import { WINGS } from '../src/design/passives.js';
import { ACTS, waystoneAL } from '../src/design/areas.js';

const quiet = process.argv.includes('--quiet'), write = !process.argv.includes('--no-write');
const broken = validate();
if (broken.length) { console.error(`Design files have ${broken.length} broken references:\n` + broken.map(e => '  ✗ ' + e).join('\n')); process.exit(1); }
const g = simGame(), warns = [], md = [];
const f0 = v => Math.round(v).toLocaleString('en-GB'), f1 = v => v.toFixed(1), f2 = v => v.toFixed(2), pc = v => Math.round(v * 100) + '%';
function chk(v, [lo, hi], what, fmt = f1) {
  const ok = v >= lo && v <= hi;
  if (!ok) warns.push(`${what}: ${fmt(v)} (target ${fmt(lo)}–${fmt(hi)})`);
  return ok ? fmt(v) : `**${fmt(v)}** ⚠️`;
}
const table = (head, rows) => { md.push('| ' + head.join(' | ') + ' |', '|' + head.map(() => ' --- ').join('|') + '|', ...rows.map(r => '| ' + r.join(' | ') + ' |'), ''); };
const minRes = ps => Math.min(ps.res.fire, ps.res.cold, ps.res.light);

md.push('# Balance report', '', 'Generated by `npm run balance` from `src/design/`. Don\'t edit by hand: change the design files and rerun.',
  'Numbers are the **par player** (`src/design/targets.js` PAR) playing every zone in order. ⚠️ marks a number outside its target band.', '');
const sumIdx = md.length; md.push('');

// ---------- Progression ----------
md.push('## Campaign, zone by zone', '');
table(['Zone', 'AL', 'Level in→out', 'Min', 'Hours', 'Fireball DPS', 'Life', 'Min res', 'Armour', 'Mana sustain'],
  g.zones.map(z => {
    const tag = z.act + ' ' + z.zone.name, ps = z.ch.ps;
    return [tag, z.zone.al, `${z.lvlIn}→${z.lvlOut}`, chk(z.minutes, T.zoneMinutes, tag + ' minutes'), f1(z.hours), f0(z.dps), f0(ps.life),
      chk(minRes(ps), T.minRes[z.act], tag + ' lowest resistance', pc), f0(ps.armour), chk(z.sustain, T.manaSustain, tag + ' mana sustain', f2)];
  }));

md.push('## Fights, zone by zone', '', 'TTK: seconds to kill one monster, single target. Hits: swings it takes that monster to kill you.', '');
table(['Zone', 'Normal life', 'TTK normal', 'TTK magic', 'TTK rare', 'Hits normal', 'Hits rare', 'Boss', 'Boss TTK', 'Boss big hits'],
  g.zones.map(z => {
    const tag = z.act + ' ' + z.zone.name, r = z.rows;
    return [tag, f0(r.normal.life), chk(r.normal.ttk, T.ttk.normal, tag + ' TTK normal', f2), chk(r.magic.ttk, T.ttk.magic, tag + ' TTK magic', f2), chk(r.rare.ttk, T.ttk.rare, tag + ' TTK rare'),
      chk(r.normal.hits, T.hitsToDie.normal, tag + ' hits to die (normal)'), chk(r.rare.hits, T.hitsToDie.rare, tag + ' hits to die (rare)'),
      z.boss ? z.boss.name : '', z.boss ? chk(z.boss.ttk, T.ttk.boss, tag + ' boss TTK', f0) : '', z.boss ? chk(z.boss.hitsBig, T.hitsToDie.bossBig, tag + ' boss big hits') : ''];
  }));

md.push('## Loot, zone by zone', '', 'Expected drops per clear (all sources).', '');
table(['Zone', 'Monsters', 'Items', 'Normal', 'Magic', 'Rare', 'Unique', 'Materials', 'Runes', 'Gold'],
  g.zones.map(z => {
    const tag = z.act + ' ' + z.zone.name, l = z.loot;
    return [tag, f0(l.monsters), chk(l.total, T.itemsPerZone, tag + ' items'), f1(l.items.normal), f1(l.items.magic), chk(l.items.rare, z.boss ? [T.raresPerZone[0], T.raresPerZone[1] * 2] : T.raresPerZone, tag + ' rares', f2), f2(l.items.unique),
      chk(l.mats, T.materialsPerZone, tag + ' materials'), f2(l.runes), f0(l.gold)];
  }));

md.push('## Acts', '');
table(['Act', 'Level after', 'Hours after', 'Uniques found'], Object.entries(g.acts).map(([id, a]) => [id,
  chk(a.lvl, T.levelAfter[id], id + ' level', f0), chk(a.hours, T.hoursAfter[id], id + ' hours'), chk(a.uniques, T.uniquesPerAct, id + ' uniques', f2)]));

// ---------- Endgame ----------
md.push('## Endgame: waystones', '', 'First map of each tier (the par player runs the listed number of maps per tier, then farms T10).', '');
table(['Tier', 'AL', 'Maps', 'Level in→out', 'Min/map', 'Hours after', 'DPS', 'Life', 'Min res', 'TTK normal', 'TTK rare', 'Hits rare', 'Boss TTK', 'Items/map'],
  g.maps.map(m => { const tag = 'T' + m.t, ps = m.ch.ps; return [tag, m.zone.al, m.runs, `${m.lvlIn}→${m.lvlOut}`, chk(m.minutes, T.mapMinutes, tag + ' minutes'), f1(m.hoursOut), f0(m.dps), f0(ps.life),
    chk(minRes(ps), T.minRes.endgame, tag + ' lowest resistance', pc), chk(m.rows.normal.ttk, T.ttk.normal, tag + ' TTK normal', f2), chk(m.rows.rare.ttk, T.ttk.rare, tag + ' TTK rare'),
    chk(m.rows.rare.hits, T.hitsToDie.rare, tag + ' hits to die (rare)'), chk(m.boss.ttk, T.ttk.boss, tag + ' boss TTK', f0), chk(m.loot.total, T.itemsPerMap, tag + ' items', f1)]; }));
const ms = g.milestones;
md.push(`Level 50 after **${ms.level50 ? chk(ms.level50, T.hoursAfter.level50, 'hours to level 50') : 'never ⚠️'}** hours; level ${g.final.lvl} after **${ms.level60 ? chk(ms.level60, T.hoursAfter.level60, 'hours to level 60') : f1(g.final.hours) + ' ⚠️'}** hours (${g.farmMaps} T10 maps after the climb).`, '');
if (!ms.level60) warns.push(`Never reached level ${LEVEL.cap} (stopped at ${g.final.lvl} after ${g.final.maps} maps)`);

// ---------- Reference tables ----------
md.push('## Reference', '', '### XP to next level', '');
const lv = [1, 5, 10, 15, 20, 25, 30, 35, 40, 45, 50, 55, 59];
table(['Level', ...lv.map(String)], [['XP', ...lv.map(l => f0(xpNeed(l)))]]);
md.push('### Monster scaling (normal, archetype ×1)', '');
const al = [1, 5, 10, 15, 20, 25, 30, 35, 40, 45, 50, 55, 60, 63];
table(['AL', ...al.map(String)], [['Life', ...al.map(l => f0(grow(SCALE.life, l)))], ['Hit', ...al.map(l => f0(grow(SCALE.dmg, l)))], ['XP', ...al.map(l => f1(grow(SCALE.xp, l)))]]);
md.push('### Skills: average hit with no gear', '');
const sl = [1, 5, 10, 15, 20];
table(['Skill', 'Unlock', ...sl.map(l => 'Lv ' + l), 'Cast s'], Object.entries(SKILLS).map(([id, s]) => [s.name, s.unlock, ...sl.map(l => f0(skillHit(s, l, sumMods([])).hit)), s.cast]));
md.push('### Affix tiers', '', 'Tier 1 is the best. Each cell: item level needed, then the roll range.', '');
table(['Affix', 'Slots', 'Tiers (best first)'], Object.entries(AFFIXES).map(([id, a]) => {
  const v = x => (a.pct || x < 1 && !a.int) && !Number.isInteger(x) ? Math.round(x * 100) + '%' : x;
  return [id + (a.pre ? ' (P)' : ' (S)'), a.slots.join(', '), affixTiers(a).map(t => `T${t.tier} i${t.ilvl}: ${v(t.min)}–${v(t.max)}`).join(' · ')];
}));
md.push('### Bases', '');
table(['Slot', 'Bases (drop level)'], Object.entries(BASES).map(([s, b]) => [s, b.map(x => `${x[0]} (${x[1]})`).join(', ')]));
md.push('### Passive tree', '');
const nodes = Object.values(WINGS).reduce((s, w) => s + w.paths.reduce((a, p) => a + p.length, 0), 0);
md.push(`${nodes} nodes; par has ${g.zones.at(-1).ch.passives.length} allocated leaving Act 3 and ${LEVEL.cap - 1 + ACTS.flatMap(a => a.zones).reduce((s, z) => s + (z.rewards?.passive || 0), 0)} at level ${LEVEL.cap}.`, '');
md.push('### Par character leaving Act 3', '');
const last = g.zones.at(-1).ch;
table(['Slot', 'Base', 'Rarity', 'Mods'], last.gear.map(i => [i.slot, i.base, i.rar, i.mods.map(([k, v]) => `${k} ${Number.isInteger(v) ? v : v < 2 ? Math.round(v * 100) + '%' : f0(v)}`).join(', ')]));
md.push(`Skill level ${last.sl}, runes: ${last.runes.join(', ') || 'none'}. Passives: ${Object.entries(last.passives.reduce((m, p) => (m[p.wing] = (m[p.wing] || 0) + 1, m), {})).map(([w, n]) => `${w} ${n}`).join(', ')}; notables ${last.passives.filter(p => p.id).map(p => p.name).join(', ')}.`, '');

md.splice(sumIdx, 1, warns.length ? `## ⚠️ ${warns.length} numbers outside their targets\n\n${warns.map(w => '- ' + w).join('\n')}\n` : '## ✅ Every number is inside its target band\n');
if (write) writeFileSync(new URL('../docs/BALANCE.md', import.meta.url), md.join('\n'));
console.log(`Balance: ${warns.length} warnings · Act 3 done at level ${g.acts.act3.lvl} (${f1(g.acts.act3.hours)} h) · level ${g.final.lvl} at ${f1(g.final.hours)} h${write ? ' · docs/BALANCE.md written' : ''}`);
if (!quiet) for (const w of warns) console.log('  ⚠️ ' + w);
